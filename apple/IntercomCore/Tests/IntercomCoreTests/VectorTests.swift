import XCTest
@testable import IntercomCore

/// Cross-platform conformance vectors: this Swift implementation authors
/// protocol/test-vectors.json (run with INTERCOM_WRITE_VECTORS=1), and both the
/// Swift and Kotlin test suites must reproduce every vector byte-exactly.
final class VectorTests: XCTestCase {
    static let groupCode = "kitchen"

    static let vectors: [(name: String, packet: Packet)] = {
        let pcm = Data((0..<Wire.frameBytes).map { UInt8(($0 &* 7) & 0xFF) })
        return [
            ("talk_start", .makeTalkStart(talkID: 0x0102_0304, ts: 1_000_000,
                                          name: "Office Mac", groupCode: groupCode)),
            ("audio", .audio(talkID: 0x0102_0304, seq: 7, ts: 1_140_000, pcm: pcm)),
            ("talk_end", .talkEnd(talkID: 0x0102_0304, lastSeq: 42)),
            ("time_ping", .timePing(talkID: 0x0102_0304, seq: 0, t1: 2_000_000)),
            ("time_pong", .timePong(talkID: 0x0102_0304, seq: 0, t1: 2_000_000, t2: 5_000_500)),
        ]
    }()

    static let clockSample = (t1: UInt64(2_000_000), t2: UInt64(5_000_500), t3: UInt64(2_001_000),
                              offset: Int64(3_000_000), rtt: UInt64(1_000))

    static var vectorsURL: URL {
        URL(fileURLWithPath: #filePath)             // …/apple/IntercomCore/Tests/IntercomCoreTests/VectorTests.swift
            .deletingLastPathComponent()            // IntercomCoreTests
            .deletingLastPathComponent()            // Tests
            .deletingLastPathComponent()            // IntercomCore
            .deletingLastPathComponent()            // apple
            .deletingLastPathComponent()            // repo root
            .appendingPathComponent("protocol/test-vectors.json")
    }

    private func currentJSON() throws -> Data {
        var root: [String: Any] = [
            "comment": "Generated by IntercomCore VectorTests; both platforms' codecs must match byte-exactly. See PROTOCOL.md.",
            "groupCode": Self.groupCode,
            "grpTag": GroupAuth.grpTag(groupCode: Self.groupCode),
            "clock": ["t1": Self.clockSample.t1, "t2": Self.clockSample.t2, "t3": Self.clockSample.t3,
                      "expectedOffsetMicros": Self.clockSample.offset, "expectedRttMicros": Self.clockSample.rtt],
        ]
        root["packets"] = Self.vectors.map { v -> [String: String] in
            ["name": v.name, "hex": v.packet.encode().map { String(format: "%02x", $0) }.joined()]
        }
        return try JSONSerialization.data(withJSONObject: root, options: [.prettyPrinted, .sortedKeys])
    }

    func testVectorsFileMatchesImplementation() throws {
        let url = Self.vectorsURL
        if ProcessInfo.processInfo.environment["INTERCOM_WRITE_VECTORS"] == "1" {
            try currentJSON().write(to: url)
        }
        let onDisk = try Data(contentsOf: url)
        XCTAssertEqual(onDisk, try currentJSON(),
                       "protocol/test-vectors.json is stale — regenerate with INTERCOM_WRITE_VECTORS=1 and review the diff")
    }

    func testVectorsDecodeAndVerify() throws {
        for v in Self.vectors {
            let decoded = Packet.decode(v.packet.encode())
            XCTAssertEqual(decoded, v.packet, v.name)
            if v.name == "talk_start" {
                XCTAssertTrue(decoded!.verifyTalkStart(groupCode: Self.groupCode))
                XCTAssertFalse(decoded!.verifyTalkStart(groupCode: "wrong"))
            }
        }
        var cs = ClockSync()
        cs.addSample(t1: Self.clockSample.t1, t2: Self.clockSample.t2, t3: Self.clockSample.t3)
        XCTAssertEqual(cs.offsetMicros, Self.clockSample.offset)
        XCTAssertEqual(cs.bestRTTMicros, Self.clockSample.rtt)
    }
}
